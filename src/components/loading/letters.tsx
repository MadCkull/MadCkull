// Spacing between letters as fraction of letter height
export const LETTER_GAP = 0.08;
// Space character width as fraction of letter height  
export const SPACE_WIDTH = 0.3;

interface LetterProps {
  char: string;
  height: number; // rendered height in px
  className?: string;
}

export function Letter({ char, height, className }: LetterProps) {
  const data = LETTER_DATA[char];
  if (!data) return null;
  
  const scale = height / data.height;
  const width = data.width * scale;
  
  return (
    <svg
      width={width}
      height={height}
      viewBox={`0 0 ${data.width} ${data.height}`}
      xmlns="http://www.w3.org/2000/svg"
      className={className}
      aria-hidden="true"
    >
      <path d={data.path} fill="currentColor" />
    </svg>
  );
}

// Calculate total width of a word at given height
export function calculateWordWidth(word: string, height: number): number {
  let totalWidth = 0;
  const gap = height * LETTER_GAP;
  
  for (let i = 0; i < word.length; i++) {
    const char = word[i];
    if (char === ' ') {
      totalWidth += height * SPACE_WIDTH;
    } else {
      const data = LETTER_DATA[char.toUpperCase()];
      if (data) {
        const scale = height / data.height;
        totalWidth += data.width * scale;
        if (i < word.length - 1 && word[i + 1] !== ' ') {
          totalWidth += gap;
        }
      }
    }
  }
  return totalWidth;
}
